import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import init, { World } from '../src/wasm/primordia_engine.js';
await init({ module_or_path: await readFile(new URL('../src/wasm/primordia_engine_bg.wasm', import.meta.url)) });
const config={ seed:8042,kind:'tidal',name:'The tidal garden',sunlight:.75,nutrients:.7,minerals:.45,temperature:.48,radiation:.18,solvent:.85,mutation:.09,capacity:4000,origin:'seeded' };
const a=new World(JSON.stringify(config)),b=new World(JSON.stringify(config));
const initial=JSON.parse(a.metadata(1));
assert.equal(initial.stats.population,160);assert.equal(initial.selected.id,1);
assert.equal(a.render_data().length,160*12);assert.equal(a.ids().length,160);assert.equal(a.field().length,1600);
a.step(400);
const evolved=JSON.parse(a.metadata(0));assert.ok(evolved.stats.births>0);assert.ok(evolved.stats.colonies>0);
b.load(a.save());a.step(200);b.step(200);
assert.deepEqual(a.render_data(),b.render_data());assert.equal(a.save(),b.save());
assert.throws(()=>b.load('{"version":900}'));
assert.throws(()=>b.configure('{"capacity":1000000}'));
assert.ok(JSON.parse(a.metadata(0)).lineages.every(l=>l.representative>0));
console.log('Bundled WebAssembly: initialization, packed arrays, evolution, selected lookup, save/resume, lineage lookup, and malformed input checks passed.');
console.log(`After ${evolved.stats.time} cycles: ${evolved.stats.population} organisms, ${evolved.stats.births} births, ${evolved.stats.colonies} colonies.`);
a.free();b.free();
